def text_w(s):
    return len(s) * 4 - 1

def draw_text(cv, s, cx, y, c):
    x = cx - text_w(s) // 2
    for ch in s.upper():
        bits = _F.get(ch)
        if bits:
            for j in range(5):
                for i in range(3):
                    if bits[j * 3 + i] == "1":
                        cv.dot(x + i, y + j, c)
        x += 4

# ---------------------------------------------------------------- estilo mínimo
GRAFITO = hx("#211D1A")
FLAT_PAPER, FLAT_FOLD = hx("#ECE4D8"), hx("#CFC6B8")

def rrect(cv, x0, y0, x1, y1, c, r=2):
    """Rectángulo sólido con esquinas redondeadas (r px)."""
    cv.rect(x0, y0, x1, y1, c)
    for k in range(r):
        n = r - k
        for dx in range(n):
            for (x, y) in ((x0 + dx, y0 + k), (x1 - dx, y0 + k), (x0 + dx, y1 - k), (x1 - dx, y1 - k)):
                cv.dot(x, y, (0, 0, 0, 0))

def tone(base, t):
    return mix(base, GRAFITO, t)

def flat_glyph(cv, name, ox, oy, c):
    cv.mask(GLYPHS[name], ox, oy, c)

# ---------------------------------------------------------------- carpetas
def folder(color="gold", glyph=None, opened=False):
    base = COLORS.get(color, color) if isinstance(color, str) else color
    back, front, ink = tone(base, .34), base, tone(base, .62)
    cv = Canvas()
    rrect(cv, 3, 5, 14, 12, back, 2)                  # pestaña
    rrect(cv, 3, 8, 28, 27, back, 2)                  # trasera
    if not opened:
        rrect(cv, 3, 12, 28, 27, front, 2)
        oy = 15
    else:
        for y in range(14, 28):                       # frontal en trapecio
            sh = round(3 * (y - 14) / 13)
            cv.rect(6 - sh, y, 31 - sh, y, front)
        rrect_fix = None
        oy = 16
    if glyph in GLYPHS:
        flat_glyph(cv, glyph, 10 if not opened else 11, oy, ink)
    return cv.im

# ---------------------------------------------------------------- ficheros
def page(color="gray", label="", glyph="text", plain=False):
    """Hoja plana con esquina doblada, un símbolo y la etiqueta en el color del tipo."""
    base = COLORS[color]
    ink = base if color not in ("yellow", "lime", "cyan") else tone(base, .25)
    cv = Canvas()
    L, R, T, B, k = 7, 24, 3, 28, 6
    rrect(cv, L, T, R, B, FLAT_PAPER, 2)
    for j in range(k + 1):                            # esquina doblada
        for i in range(k + 1):
            x, y = R - k + i, T + j
            if i > j:
                cv.dot(x, y, (0, 0, 0, 0))
            elif i < j - 0 and i > 0 and j < k:
                cv.dot(x, y, FLAT_FOLD)
    if glyph == "text":
        for n, yy in enumerate((9, 12, 15)):
            cv.rect(11, yy, 11 + (12 if n < 2 else 7), yy + 1, mix(FLAT_PAPER, GRAFITO, .22))
    elif glyph in GLYPHS:
        flat_glyph(cv, glyph, 10, 9 if label else 11, ink)
    if label:
        draw_text(cv, label, (L + R) // 2 + 1, 22, ink)
    return cv.im

# ---------------------------------------------------------------- utilidades
def pixelize(png_path_or_img, size=N, colors=20):
    """Reduce una imagen suave a rejilla `size` con alfa duro y paleta corta."""
    im = png_path_or_img if hasattr(png_path_or_img, "size") else Image.open(png_path_or_img)
    im = im.convert("RGBA")
    alpha = im.getchannel("A").point(lambda a: 255 if a >= 110 else 0)
    rgb = Image.new("RGB", im.size, (0, 0, 0))
    rgb.paste(im, mask=im.getchannel("A"))
    q = rgb.quantize(colors=colors, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert("RGB")
    out = q.convert("RGBA")
    out.putalpha(alpha)
    return out
