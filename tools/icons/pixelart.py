def shades(base):
    """Rampa con cambio de matiz: luces cálidas, sombras frías, contorno violeta oscuro."""
    return dict(hi=mix(base, WARM, .62), light=mix(base, WARM, .30), base=base,
                shade=mix(base, COOL, .30), dark=mix(base, COOL, .52), line=mix(base, DEEP, .74))

