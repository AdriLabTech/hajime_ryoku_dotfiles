def hx(s):
    s = s.lstrip("#")
    return tuple(int(s[i:i + 2], 16) for i in (0, 2, 4)) + (255,)

def mix(c, o, t):
    return tuple(round(c[i] * (1 - t) + o[i] * t) for i in range(3)) + (255,)

